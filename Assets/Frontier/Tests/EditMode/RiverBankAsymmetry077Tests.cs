        static float HistoricalBank(MapLayout layout,Vector2 point)
        {
            if(!layout.HasWater||layout.Id==MapTopology.River)return 0;
            float d=layout.SignedBankDistance(point);
            if(d<=0)return Mathf.Lerp(layout.WaterHeight-.02f,-.9f,Mathf.SmoothStep(0,1,-d/4));
            return (layout.WaterHeight-.02f)*(1-Mathf.SmoothStep(0,1,d/3));
        }
        static Color HistoricalLayers(MapLayout layout,Vector2 point)
        {
            float distance=layout.SignedBankDistance(point);
            float tidal=layout.Id==MapTopology.Estuary?Mathf.SmoothStep(0,1,(point.y-78)/18f):0;
            float noise=Mathf.PerlinNoise(point.x*.13f+3,point.y*.11f+8)-.5f;
            float damp=1-Mathf.SmoothStep(0,1,(distance-.25f-noise*.25f)/Mathf.Lerp(2.6f,3.7f,tidal));
